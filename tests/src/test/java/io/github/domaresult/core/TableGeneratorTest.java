package io.github.domaresult.core;

import static org.junit.jupiter.api.Assertions.*;
import io.github.domaresult.core.TableGenerator.*;
import java.net.URLClassLoader;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.sql.*;
import java.util.*;
import javax.tools.*;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class TableGeneratorTest {
    @TempDir Path temp;
    private final TableGenerator generator = new TableGenerator();
    private static final String URL = "jdbc:h2:mem:table_gen";
    private Connection database() throws Exception {
        Connection db = DriverManager.getConnection(URL);
        try (Statement statement = db.createStatement()) {
            statement.execute("CREATE SCHEMA APP");
            statement.execute("CREATE TABLE APP.EMPLOYEE (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NAME VARCHAR(80), CREATED_DATETIME TIMESTAMP, VERSION_NO INTEGER)");
            statement.execute("CREATE TABLE APP.AUDIT_LOG (MESSAGE VARCHAR(100))");
            statement.execute("CREATE TABLE APP.MEMBERSHIP (USER_ID BIGINT, GROUP_ID INTEGER, PRIMARY KEY(USER_ID,GROUP_ID))");
            statement.execute("CREATE VIEW APP.EMPLOYEE_VIEW AS SELECT ID,NAME FROM APP.EMPLOYEE");
            statement.execute("INSERT INTO APP.EMPLOYEE (ID,NAME,VERSION_NO) VALUES (1,'Alice',0)");
        }
        return db;
    }
    private PreviewExecution.Cancellation cancellation() { return new PreviewExecution.Cancellation(); }
    private Set<Table> chosen(Connection db, String... names) throws Exception {
        Set<String> select = Set.of(names);
        return new HashSet<>(generator.tables(db, URL, "APP", false, cancellation()).stream().filter(t -> select.contains(t.name())).toList());
    }
    private Options options(boolean listener) { return new Options("example.entity", "example.dao", listener, true, null, null); }
    private List<Artifact> generate(Connection db, Options options, String... names) throws Exception {
        return generator.generate(db, URL, "APP", false, chosen(db, names), options, cancellation());
    }
    @Test void listsTablesAndOptionalViewsWithoutReadingColumns() throws Exception {
        try (var db = database()) {
            assertEquals(List.of("AUDIT_LOG", "EMPLOYEE", "MEMBERSHIP"), generator.tables(db, URL, "APP", false, cancellation()).stream().map(Table::name).toList());
            assertEquals(4, generator.tables(db, URL, "APP", true, cancellation()).size());
            assertFalse(db.isClosed());
        }
    }
    @Test void officialPipelineProducesEntityDaoListenerAndKeySqlThatCompileAndRun() throws Exception {
        try (var db = database()) {
            var output = generate(db, options(true), "EMPLOYEE");
            assertEquals(5, output.size());
            String entity = output.stream().filter(a -> a.kind() == Kind.ENTITY).findFirst().orElseThrow().source();
            assertTrue(entity.contains("private Long id;"));
            assertTrue(entity.contains("@Id")); assertTrue(entity.contains("@GeneratedValue(strategy = GenerationType.IDENTITY)"));
            assertTrue(entity.contains("@Version")); assertTrue(entity.contains("@Column(name = \"NAME\")"));
            assertTrue(entity.contains("import org.seasar.doma.Column;"));
            assertTrue(entity.contains("schema = \"APP\""));
            var sql = output.stream().filter(a -> a.kind() == Kind.SQL).toList();
            assertEquals(Set.of("selectById.sql", "selectByIdAndVersion.sql"), new HashSet<>(sql.stream().map(a -> Path.of(a.path()).getFileName().toString()).toList()));
            Path classes = compile(output);
            try (URLClassLoader loader = new URLClassLoader(new java.net.URL[]{classes.toUri().toURL()}, getClass().getClassLoader())) {
                var config = new org.seasar.doma.jdbc.Config() {
                    @Override public javax.sql.DataSource getDataSource() { var ds = new org.h2.jdbcx.JdbcDataSource(); ds.setURL(URL + ";SCHEMA=APP"); return ds; }
                    @Override public org.seasar.doma.jdbc.dialect.Dialect getDialect() { return new org.seasar.doma.jdbc.dialect.H2Dialect(); }
                    @Override public org.seasar.doma.jdbc.ClassHelper getClassHelper() {
                        return new org.seasar.doma.jdbc.ClassHelper() {
                            @Override public <T> Class<T> forName(String name) throws ClassNotFoundException { return (Class<T>) loader.loadClass(name); }
                        };
                    }
                };
                Class<?> dao = loader.loadClass("example.dao.EmployeeDaoImpl");
                Object instance = dao.getConstructor(org.seasar.doma.jdbc.Config.class).newInstance(config);
                Object employee;
                ClassLoader previous = Thread.currentThread().getContextClassLoader();
                try {
                    Thread.currentThread().setContextClassLoader(loader);
                    employee = dao.getMethod("selectById", Long.class).invoke(instance, 1L);
                } finally { Thread.currentThread().setContextClassLoader(previous); }
                assertEquals("Alice", employee.getClass().getMethod("getName").invoke(employee));
                assertFalse(db.isClosed());
                try (Statement statement = db.createStatement(); ResultSet rows = statement.executeQuery("SELECT COUNT(*) FROM APP.EMPLOYEE")) { rows.next(); assertEquals(1, rows.getInt(1)); }
            }
        }
    }
    @Test void compositesAndTablesWithoutKeysFollowOfficialSqlRules() throws Exception {
        try (var db = database()) {
            var noKey = generate(db, options(false), "AUDIT_LOG");
            assertEquals(2, noKey.size()); assertTrue(noKey.stream().noneMatch(a -> a.kind() == Kind.SQL));
            var composite = generate(db, options(false), "MEMBERSHIP");
            assertEquals(3, composite.size());
            String sql = composite.stream().filter(a -> a.kind() == Kind.SQL).findFirst().orElseThrow().source();
            assertTrue(sql.contains("USER_ID")); assertTrue(sql.contains("GROUP_ID"));
            compile(composite);
        }
    }
    @Test void reusesUtf8NamePropertiesAndExistingFreemarkerTemplateDirectory() throws Exception {
        Path mapping = temp.resolve("name.properties");
        Files.writeString(mapping, ".*Datetime$=java.time.LocalDateTime\n");
        Path templates = Files.createDirectory(temp.resolve("templates"));
        Files.writeString(templates.resolve("dao.ftl"), "package ${packageName};\n// カスタムテンプレート\npublic interface ${simpleName} {}\n");
        Files.writeString(templates.resolve("selectAll.sql.ftl"), "select * from ${entityDesc.tableName}\n");
        try (var db = database()) {
            var output = generate(db, new Options("example.entity", "example.dao", false, true, mapping, templates), "EMPLOYEE");
            assertTrue(output.stream().filter(a -> a.kind() == Kind.ENTITY).findFirst().orElseThrow().source().contains("private LocalDateTime createdDatetime;"));
            assertTrue(output.stream().filter(a -> a.kind() == Kind.DAO).findFirst().orElseThrow().source().contains("カスタムテンプレート"));
            assertTrue(output.stream().anyMatch(a -> a.path().equals("META-INF/example/dao/EmployeeDao/selectAll.sql") && a.source().contains("EMPLOYEE")));
        }
    }
    @Test void refusesMissingSelectionsAndCollidingNamesAcrossSchemas() throws Exception {
        try (var db = database()) {
            assertThrows(GenerationException.class, () -> generator.generate(db, URL, "APP", false, Set.of(), options(false), cancellation()));
            assertThrows(GenerationException.class, () -> generator.generate(db, URL, "APP", false, Set.of(new Table(null,"APP","MISSING")), options(false), cancellation()));
            try (var statement = db.createStatement()) { statement.execute("CREATE SCHEMA OTHER"); statement.execute("CREATE TABLE OTHER.EMPLOYEE(ID BIGINT PRIMARY KEY)"); }
            Set<Table> selected = new HashSet<>(generator.tables(db, URL, "%", false, cancellation()).stream().filter(t -> t.name().equals("EMPLOYEE")).toList());
            assertEquals(2, selected.size());
            assertTrue(assertThrows(GenerationException.class, () -> generator.generate(db, URL, "%", false, selected, options(false), cancellation())).getMessage().contains("same file"));
        }
    }
    @Test void copiedAndEditedTemplatesAreAppliedOnTheVeryNextPreviewWithoutTemplateCacheDelay() throws Exception {
        var files = new TemplateFiles(temp.resolve("templates")); files.copyMissingDefaults();
        var options = new Options("example.entity", "example.dao", true, true, null, files.directory());
        try (var db = database()) {
            var first = generate(db, options, "EMPLOYEE");
            assertTrue(first.stream().filter(a -> a.kind() == Kind.ENTITY).findFirst().orElseThrow().source().contains("private Long id;"));
            for (String name : List.of("entity.ftl", "dao.ftl")) {
                var before = files.read(name); files.save(before, "// Edited " + name + "\n" + before.source());
            }
            files.save(files.read("lib.ftl"), "<#assign author = \"Template Editor\">\n");
            var next = generate(db, options, "EMPLOYEE");
            assertTrue(next.stream().filter(a -> a.kind() == Kind.ENTITY).findFirst().orElseThrow().source().contains("// Edited entity.ftl"));
            assertTrue(next.stream().filter(a -> a.kind() == Kind.DAO).findFirst().orElseThrow().source().contains("// Edited dao.ftl"));
            assertTrue(next.stream().filter(a -> a.kind() == Kind.LISTENER).findFirst().orElseThrow().source().contains("@author Template Editor"));
            compile(next);
        }
    }
    @Test void templateEvaluationErrorsIdentifyTheTemplateAndLineWithoutLoggingModelValues() throws Exception {
        var files = new TemplateFiles(temp.resolve("templates")); files.copyMissingDefaults();
        files.save(files.read("dao.ftl"), "${missingProperty}\n");
        try (var db = database()) {
            var failure = assertThrows(GenerationException.class, () -> generate(db,
                    new Options("example.entity", "example.dao", false, true, null, files.directory()), "EMPLOYEE"));
            assertTrue(failure.getMessage().contains("FTL processing failed in dao.ftl at line 1"));
            assertFalse(failure.getMessage().contains("missingProperty"));
        }
    }
    @Test void editedNamePropertiesAreReloadedByOfficialTableGenerationOnTheNextPreview() throws Exception {
        var file = new NameMappingsFile(temp.resolve("name.properties"));
        var saved = file.save(file.read(), ".*Datetime$=java.time.LocalDateTime\n");
        var options = new Options("example.entity", "example.dao", false, true, file.path(), null);
        try (var db = database()) {
            var first = generate(db, options, "EMPLOYEE");
            assertTrue(first.stream().filter(a -> a.kind()==Kind.ENTITY).findFirst().orElseThrow().source().contains("private LocalDateTime createdDatetime;"));
            file.save(saved, ".*Datetime$=java.sql.Timestamp\n");
            var next = generate(db, options, "EMPLOYEE");
            assertTrue(next.stream().filter(a -> a.kind()==Kind.ENTITY).findFirst().orElseThrow().source().contains("private Timestamp createdDatetime;"));
            compile(next);
        }
    }
    @Test void rejectsPathsEscapingOutputFoldersAndInvalidPackages() {
        for (String path : List.of("../outside.java", "/outside.java", "a/../../outside.sql", "a\\..\\outside.java")) {
            assertThrows(GenerationException.class, () -> new Artifact(Kind.SQL, path, ""));
        }
        assertThrows(GenerationException.class, () -> new Options("bad-package", "example.dao", false, false, null, null));
    }
    private Path compile(List<Artifact> artifacts) throws Exception {
        Path sources = Files.createTempDirectory(temp, "sources-");
        Path classes = Files.createTempDirectory(temp, "classes-");
        List<Path> java = new ArrayList<>();
        for (Artifact artifact : artifacts) {
            Path destination = (artifact.kind() == Kind.SQL ? classes : sources).resolve(artifact.path());
            Files.createDirectories(destination.getParent()); Files.writeString(destination, artifact.source());
            if (artifact.kind() != Kind.SQL) java.add(destination);
        }
        var compiler = ToolProvider.getSystemJavaCompiler();
        var diagnostics = new DiagnosticCollector<JavaFileObject>();
        try (var manager = compiler.getStandardFileManager(diagnostics, null, StandardCharsets.UTF_8)) {
            var opts = List.of("--release", "8", "-classpath", System.getProperty("java.class.path"), "-d", classes.toString(), "-s", classes.toString(), "-processor", "org.seasar.doma.internal.apt.processor.EntityProcessor,org.seasar.doma.internal.apt.processor.DaoProcessor", "-Adoma.resources.dir=" + classes);
            assertTrue(compiler.getTask(null, manager, diagnostics, opts, null, manager.getJavaFileObjectsFromPaths(java)).call(), () -> diagnostics.getDiagnostics().toString());
        }
        return classes;
    }
}
